export function translate(lang, key, vars) {
  const template = STRINGS[lang]?.[key] ?? STRINGS.nl[key] ?? key
  if (!vars) return template
  return template.replace(/\{\{(\w+)\}\}/g, (_, name) => vars[name] ?? '')
}
